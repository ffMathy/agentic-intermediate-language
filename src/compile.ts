// The build loop behind `ail build`, the `submit` door, and deterministic glue.
//
// The compile loop is code, not prompt: hash → cache check → encapsulated
// context → model → verify → retry with failures → lock. A model can only
// write the files its node owns, and nothing is accepted unless verify passes.
import { existsSync, mkdirSync, readFileSync, writeFileSync, rmSync } from "node:fs";
import { dirname, join, relative, resolve } from "node:path";
import { buildContext } from "./context.ts";
import { compileHash, oracleHash, sha256 } from "./hash.ts";
import { fileHash, readLock, writeLock } from "./lock.ts";
import { parseFile, type AilNode } from "./parse.ts";
import { plan } from "./plan.ts";
import { AIL_HOME, isCompilable, kebab, modulePath, specModulePath, topoByUses, type Project } from "./project.ts";
import type { Provider } from "./providers/index.ts";
import { checkHeader, checkPath, checksDir, derivedCheckFile, loadPrompt, needsDerivedCheck, stampCheck, verifyNode, type VerifyResult } from "./verify.ts";
export { checkPath, loadPrompt } from "./verify.ts";

export interface ParsedReply { stop: string | null; files: Record<string, string> }

export function parseReply(text: string): ParsedReply {
  const stop = /^STOP:\s*(.+)$/m.exec(text);
  const files: Record<string, string> = {};
  for (const m of text.matchAll(/^=== FILE: (.+?) ===\r?\n([\s\S]*?)\r?\n=== END ===/gm)) {
    let body = m[2]!;
    const fenced = /^```[\w-]*\r?\n([\s\S]*?)\r?\n```\s*$/.exec(body);
    if (fenced) body = fenced[1]!;
    files[m[1]!.trim()] = body.endsWith("\n") ? body : body + "\n";
  }
  return { stop: Object.keys(files).length ? null : (stop?.[1]?.trim() ?? null), files };
}

// --- glue ------------------------------------------------------------------

export function tokensCss(p: Project): string {
  const lines = Object.entries(p.tokens).filter(([, v]) => v).sort(([a], [b]) => a.localeCompare(b))
    .map(([k, v]) => `  --${k.replace(/\./g, "-")}: ${v};`);
  return `/* Generated by ail from the catalog. Do not edit. */\n:root {\n${lines.join("\n")}\n}\n`;
}

/** Spec files under a folder, as data: path (relative to that folder) and text, sorted by path. */
function specFilesIn(dir: string): { path: string; text: string }[] {
  if (!existsSync(dir)) return [];
  return [...new Bun.Glob("**/*.ail.md").scanSync({ cwd: dir })]
    .filter((f) => !/(^|\/)(node_modules|\.[^/]+)\//.test(f))
    .map((f) => ({ path: f.split("\\").join("/"), text: readFileSync(join(dir, f), "utf8") }))
    .sort((a, b) => explorerOrder(a.path, b.path));
}

/** Explorer order: within each folder, its own files first, then its subfolders, each by name. */
export function explorerOrder(a: string, b: string): number {
  const x = a.split("/"), y = b.split("/");
  for (let i = 0; i < Math.min(x.length, y.length); i++) {
    if (x[i] === y[i]) continue;
    const xFile = i === x.length - 1, yFile = i === y.length - 1;
    if (xFile !== yFile) return xFile ? -1 : 1;
    return x[i]!.localeCompare(y[i]!);
  }
  return x.length - y.length;
}

/** Spec files (of this project, or of several) as a TypeScript data module, for pages that show them. */
export function specModule(p: Project): string {
  const mod = p.config.specModule;
  const projects = typeof mod === "object" && mod
    ? mod.projects.map((q) => ({ key: q.key, name: q.name, dir: resolve(p.root, q.dir) }))
    : [{ key: "this", name: "This project", dir: p.specRoot }];
  const data = projects.map((q) => {
    const files = specFilesIn(q.dir);
    const nodeCount = files.reduce((sum, f) => sum + parseFile(f.path, f.text).nodes.length, 0);
    return { key: q.key, name: q.name, nodeCount, files };
  });
  return [
    "// Generated by `ail build` from spec files. Do not edit.",
    "export type SpecFile = { path: string; text: string };",
    "export type SpecProject = { key: string; name: string; nodeCount: number; files: SpecFile[] };",
    `export const specProjects: SpecProject[] = ${JSON.stringify(data, null, 2)};`,
    "",
  ].join("\n");
}

/** Deterministic, model-free output: the catalog tokens as CSS variables, and the spec module when configured. */
export function renderGlue(p: Project): Record<string, string> {
  const out: Record<string, string> = {};
  const css = p.target?.settings["tokens-css"];
  if (css) out[css] = tokensCss(p);
  const sm = specModulePath(p);
  if (sm) out[sm] = specModule(p);
  return out;
}

/** Glue files whose content no longer matches what the spec would produce. */
export function staleGlue(p: Project): string[] {
  return Object.entries(renderGlue(p))
    .filter(([rel, body]) => !existsSync(join(p.root, rel)) || readFileSync(join(p.root, rel), "utf8") !== body)
    .map(([rel]) => rel);
}

/** Is a project-relative path inside the target's `generated` globs? */
export function isGenerated(p: Project, rel: string): boolean {
  if (rel.startsWith("..") || rel.startsWith("/")) return false;
  const globs = (p.target?.settings["generated"] ?? "").split(/[\s,]+/).filter(Boolean);
  return globs.some((g) => new Bun.Glob(g).match(rel));
}

export function writeGlue(p: Project): string[] {
  const glue = renderGlue(p);
  const lock = readLock(p);
  const written: string[] = [];
  for (const [rel, body] of Object.entries(glue)) {
    const abs = join(p.root, rel);
    if (existsSync(abs) && readFileSync(abs, "utf8") === body) { lock.glue[rel] = sha256(body); continue; }
    mkdirSync(dirname(abs), { recursive: true });
    writeFileSync(abs, body);
    lock.glue[rel] = sha256(body);
    written.push(rel);
  }
  // Glue that is no longer produced is forgotten. It is deleted only when it
  // is untouched and still inside the target's generated paths, so a file
  // that became hand-written (like index.html) is never removed.
  if (p.target) for (const [rel, h] of Object.entries(lock.glue)) {
    if (rel in glue) continue;
    if (fileHash(p, rel) === h && isGenerated(p, rel)) rmSync(join(p.root, rel));
    delete lock.glue[rel];
  }
  writeLock(p, lock);
  return written;
}

// --- submit ------------------------------------------------------------------

export interface SubmitResult { ok: boolean; node: string; error?: string; verify?: VerifyResult }

/**
 * Write a node's files, verify them, and record them in the lock — or roll
 * back. This is the single door through which generated code enters the
 * tree, whether `ail build` called a model or an agent wrote it.
 *
 * `files` holds the node's module and, optionally, its derived check
 * (checks/<dir>/<kebab>.test.ts(x)); the check is pinned to the current spec.
 * Deterministic glue is refreshed and orphaned output pruned on the way.
 */
export function submit(p: Project, n: AilNode, files: Record<string, string>, by = "agent"): SubmitResult {
  const path = modulePath(p, n);
  if (!path || !isCompilable(p, n)) return { ok: false, node: n.name, error: `${n.name} is not a compilable node` };
  const check = needsDerivedCheck(n) ? checkPath(p, n) : null;
  const extra = Object.keys(files).filter((f) => f !== path && f !== check);
  if (extra.length) return { ok: false, node: n.name, error: `${n.name} may only write ${path}${check ? ` and ${check}` : ""}; refused ${extra.join(", ")}` };
  if (!(path in files)) return { ok: false, node: n.name, error: `no content for ${path}` };

  writeGlue(p);
  prune(p);
  const writes: [string, string][] = [[path, files[path]!]];
  if (check && files[check] !== undefined) writes.unshift([check, stampCheck(p, n, files[check]!)]);
  const backups = writes.map(([rel]) => [rel, existsSync(join(p.root, rel)) ? readFileSync(join(p.root, rel), "utf8") : null] as const);
  for (const [rel, body] of writes) { mkdirSync(dirname(join(p.root, rel)), { recursive: true }); writeFileSync(join(p.root, rel), body); }
  const verify = verifyNode(p, n, { checkDrift: false });
  if (!verify.ok) {
    for (const [rel, old] of backups) { if (old === null) rmSync(join(p.root, rel)); else writeFileSync(join(p.root, rel), old); }
    return { ok: false, node: n.name, verify, error: "verification failed; previous version restored" };
  }
  const lock = readLock(p);
  // The node moved (e.g. into a subfolder): remove its old, untouched output.
  for (const [old, h] of Object.entries(lock.nodes[n.name]?.files ?? {}))
    if (old !== path && fileHash(p, old) === h) rmSync(join(p.root, old));
  lock.nodes[n.name] = { hash: compileHash(p, n), files: { [path]: sha256(files[path]!) }, by };
  writeLock(p, lock);
  return { ok: true, node: n.name, verify };
}

/**
 * Drop lock entries for nodes that no longer exist (or are no longer
 * compilable) and delete their generated files, unless someone edited them.
 */
export function prune(p: Project): { removed: string[]; kept: string[] } {
  // Without a target nothing is compilable, and pruning would delete everything.
  if (!p.target) return { removed: [], kept: [] };
  const lock = readLock(p);
  const removed: string[] = [], kept: string[] = [];
  for (const [name, entry] of Object.entries(lock.nodes)) {
    const n = p.nodes.get(name);
    if (n && isCompilable(p, n)) continue;
    for (const [file, h] of Object.entries(entry.files)) {
      const actual = fileHash(p, file);
      if (actual === h) { rmSync(join(p.root, file)); removed.push(file); }
      else if (actual !== null) kept.push(file);
    }
    delete lock.nodes[name];
  }
  writeLock(p, lock);
  // Derived checks of nodes that are gone, or that moved to another folder.
  const dir = checksDir(p);
  if (existsSync(dir)) for (const rel of new Bun.Glob("**/*.test.{ts,tsx}").scanSync({ cwd: dir })) {
    const abs = join(dir, rel);
    const name = /^\/\/ ail-derived-from:\s*(\w+)@/.exec(readFileSync(abs, "utf8"))?.[1];
    if (!name) continue;
    const n = p.nodes.get(name);
    const file = relative(p.root, abs);
    if (!n || !needsDerivedCheck(n) || checkPath(p, n) !== file) { rmSync(abs); removed.push(file); }
  }
  return { removed, kept };
}

// --- compile -----------------------------------------------------------------

export interface CompileOptions {
  provider: Provider;
  /** How many nodes may compile at once (default 4). */
  jobs?: number;
  force?: boolean;
  maxAttempts?: number;
  temperature?: number;
  log?: (msg: string) => void;
}

export interface CompileOutcome { node: string; status: "fresh" | "compiled" | "stopped" | "failed" | "skipped"; attempts: number; detail: string }

export function compileTask(p: Project, n: AilNode): string {
  return [
    buildContext(p, n),
    "## Task",
    `Implement ${n.name} as specified. The only file you may write is ${modulePath(p, n)}.`,
    "Reply with exactly one block:",
    `=== FILE: ${modulePath(p, n)} ===`,
    "<complete file contents>",
    "=== END ===",
    "If you would have to choose anything the spec, the target or the catalog does not determine,",
    "and it is not listed in `free`, reply instead with a single line: STOP: <the question the spec must answer>",
  ].join("\n");
}

export async function compileNode(p: Project, n: AilNode, opts: CompileOptions, sample?: number): Promise<{ reply: ParsedReply; raw: string }> {
  const raw = await opts.provider.complete({
    system: loadPrompt("compile-leaf"),
    prompt: compileTask(p, n),
    temperature: opts.temperature,
    meta: { node: n.name, sample, purpose: "compile" },
  });
  return { reply: parseReply(raw), raw };
}

/** Run `fn` over `items` with at most `limit` running at once; results keep input order. */
export async function mapLimit<T, R>(items: T[], limit: number, fn: (item: T) => Promise<R>): Promise<R[]> {
  const out: R[] = new Array(items.length);
  let next = 0;
  const worker = async () => { while (next < items.length) { const i = next++; out[i] = await fn(items[i]!); } };
  await Promise.all(Array.from({ length: Math.min(validJobs(limit), items.length) }, worker));
  return out;
}

/** A concurrency limit, made safe: anything but a positive integer means 1. */
export const validJobs = (n: number) => (Number.isInteger(n) && n >= 1 ? n : 1);

/** A simple counting semaphore. */
function semaphore(requested: number) {
  const limit = validJobs(requested);
  let active = 0;
  const queue: (() => void)[] = [];
  return async <T>(fn: () => Promise<T>): Promise<T> => {
    if (active >= limit) await new Promise<void>((r) => queue.push(r));
    active++;
    try { return await fn(); } finally { active--; queue.shift()?.(); }
  };
}

/**
 * Compile every target node that isn't fresh. Independent nodes compile
 * concurrently (up to `jobs`); a node starts only once the nodes it uses are
 * built. `submit` is synchronous, so lock writes never interleave.
 */
export async function compile(p: Project, names: string[], opts: CompileOptions): Promise<CompileOutcome[]> {
  const log = opts.log ?? (() => {});
  const glue = writeGlue(p);
  if (glue.length) log(`glue: wrote ${glue.join(", ")}`);
  const pruned = prune(p);
  if (pruned.removed.length) log(`pruned: ${pruned.removed.join(", ")}`);
  if (pruned.kept.length) log(`left hand-edited files of removed nodes in place: ${pruned.kept.join(", ")}`);
  const statuses = new Map(plan(p).map((e) => [e.node, e.status]));
  const targets = topoByUses(p, p.ordered.filter((n) => isCompilable(p, n) && (!names.length || names.includes(n.name))));
  const limit = semaphore(opts.jobs ?? 4);
  const results = new Map<string, Promise<CompileOutcome>>();
  const built = (o: { status: string }) => o.status === "fresh" || o.status === "compiled";

  const run = async (n: AilNode): Promise<CompileOutcome> => {
    const deps = n.uses.map((u) => p.nodes.get(u)).filter((d): d is AilNode => !!d && isCompilable(p, d));
    const depOutcomes = await Promise.all(deps.map((d) => results.get(d.name) ?? Promise.resolve({ status: statuses.get(d.name) ?? "missing" })));
    const waiting = deps.filter((_, i) => !built(depOutcomes[i]!)).map((d) => d.name);
    if (waiting.length) return { node: n.name, status: "skipped", attempts: 0, detail: `waiting for ${waiting.join(", ")}` };
    if (!opts.force && statuses.get(n.name) === "fresh") return { node: n.name, status: "fresh", attempts: 0, detail: "cache hit" };
    return limit(async () => {
      let prompt = compileTask(p, n);
      const max = opts.maxAttempts ?? 3;
      for (let attempt = 1; attempt <= max; attempt++) {
        log(`${n.name}: attempt ${attempt} with ${opts.provider.id}`);
        let raw: string;
        try {
          raw = await opts.provider.complete({ system: loadPrompt("compile-leaf"), prompt, temperature: opts.temperature, meta: { node: n.name, sample: attempt - 1, purpose: "compile" } });
        } catch (e) {
          return { node: n.name, status: "failed" as const, attempts: attempt, detail: `the model call failed: ${(e as Error).message}` };
        }
        const reply = parseReply(raw);
        if (reply.stop) return { node: n.name, status: "stopped" as const, attempts: attempt, detail: reply.stop };
        const res = submit(p, n, reply.files, opts.provider.id);
        if (res.ok) return { node: n.name, status: "compiled" as const, attempts: attempt, detail: res.verify?.checks.map((c) => c.kind).join(", ") ?? "" };
        const failures = res.verify ? res.verify.checks.filter((c) => !c.ok).map((c) => `- ${c.kind}: ${c.detail}`).join("\n") : `- ${res.error}`;
        log(`${n.name}: attempt ${attempt} rejected\n${failures}`);
        prompt = `${compileTask(p, n)}\n\n## Your previous attempt was rejected\n${failures}\n\nPrevious attempt:\n${raw}`;
      }
      const check = needsDerivedCheck(n) ? derivedCheckFile(p, n).file : null;
      return { node: n.name, status: "failed" as const, attempts: max, detail: `no attempt passed verification: the node may be under-specified or infeasible${check ? `, or its derived check ${relative(p.root, check)} may itself be wrong (it was generated, so review it)` : ""}` };
    });
  };
  // Targets are in dependency order, so every dependency's promise exists before its dependants start.
  for (const n of targets) results.set(n.name, run(n));
  return Promise.all(targets.map((n) => results.get(n.name)!));
}

