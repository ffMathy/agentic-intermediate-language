// `ail compile`, `ail submit`, `ail derive` and deterministic glue.
//
// The compile loop is code, not prompt: hash → cache check → encapsulated
// context → model → verify → retry with failures → lock. A model can only
// write the files its node owns, and nothing is accepted unless verify passes.
import { existsSync, mkdirSync, readFileSync, readdirSync, statSync, writeFileSync, rmSync } from "node:fs";
import { dirname, join, relative } from "node:path";
import { buildContext, importSpecifier } from "./context.ts";
import { compileHash, oracleHash, sha256 } from "./hash.ts";
import { readLock, writeLock } from "./lock.ts";
import type { AilNode } from "./parse.ts";
import { plan } from "./plan.ts";
import { AIL_HOME, isCompilable, kebab, modulePath, topoByUses, type Project } from "./project.ts";
import type { Provider } from "./providers/index.ts";
import { checksDir, derivedCheckFile, needsDerivedCheck, verifyNode, type VerifyResult } from "./verify.ts";

export function loadSkill(name: string): string {
  const f = join(AIL_HOME, "skills", name, "SKILL.md");
  return readFileSync(f, "utf8").replace(/^---[\s\S]*?---\s*/, "").trim();
}

export interface ParsedReply { stop: string | null; files: Record<string, string> }

export function parseReply(text: string): ParsedReply {
  const stop = /^STOP:\s*(.+)$/m.exec(text);
  const files: Record<string, string> = {};
  for (const m of text.matchAll(/^=== FILE: (.+?) ===\r?\n([\s\S]*?)\r?\n=== END ===/gm)) {
    let body = m[2]!;
    const fenced = /^```[\w-]*\r?\n([\s\S]*?)\r?\n```\s*$/.exec(body);
    if (fenced) body = fenced[1]!;
    files[m[1]!.trim()] = body.endsWith("\n") ? body : body + "\n";
  }
  return { stop: Object.keys(files).length ? null : (stop?.[1]?.trim() ?? null), files };
}

// --- glue ------------------------------------------------------------------

export function tokensCss(p: Project): string {
  const lines = Object.entries(p.tokens).filter(([, v]) => v).sort(([a], [b]) => a.localeCompare(b))
    .map(([k, v]) => `  --${k.replace(/\./g, "-")}: ${v};`);
  return `/* Generated by ail from the catalog. Do not edit. */\n:root {\n${lines.join("\n")}\n}\n`;
}

function listFiles(dir: string, base = dir): string[] {
  return readdirSync(dir).sort().flatMap((f) => {
    const p = join(dir, f);
    return statSync(p).isDirectory() ? listFiles(p, base) : [relative(base, p)];
  });
}

/** Deterministic, LLM-free output: tokens.css plus the profile's glue templates. */
export function renderGlue(p: Project): Record<string, string> {
  const out: Record<string, string> = {};
  const s = p.profile?.settings ?? {};
  if (s["tokens-css"]) out[s["tokens-css"]] = tokensCss(p);
  const sys = p.ordered.find((n) => n.kind === "system" && n.entry);
  const gdir = p.profile ? join(p.profile.dir, "glue") : "";
  if (sys && gdir && existsSync(gdir)) {
    const entry = p.nodes.get(sys.entry!)!;
    const entryPath = modulePath(p, entry);
    for (const rel of listFiles(gdir)) {
      const vars: Record<string, string> = {
        title: sys.name.replace(/([a-z])([A-Z])/g, "$1 $2"),
        entry: entry.name,
        entryKebab: kebab(entry.name),
        entryImport: entryPath ? importSpecifier(rel, entryPath) : "",
      };
      out[rel] = readFileSync(join(gdir, rel), "utf8").replace(/\{\{(\w+)\}\}/g, (_, k) => vars[k] ?? "");
    }
  }
  return out;
}

export function writeGlue(p: Project): string[] {
  const glue = renderGlue(p);
  const lock = readLock(p);
  const written: string[] = [];
  for (const [rel, body] of Object.entries(glue)) {
    const abs = join(p.root, rel);
    if (existsSync(abs) && readFileSync(abs, "utf8") === body) { lock.glue[rel] = sha256(body); continue; }
    mkdirSync(dirname(abs), { recursive: true });
    writeFileSync(abs, body);
    lock.glue[rel] = sha256(body);
    written.push(rel);
  }
  writeLock(p, lock);
  return written;
}

// --- submit ------------------------------------------------------------------

export interface SubmitResult { ok: boolean; node: string; error?: string; verify?: VerifyResult }

/**
 * Write a node's files, verify them, and record them in the lock — or roll
 * back. This is the single door through which generated code enters the
 * tree, whether a model was called by `ail compile` or an agent wrote it.
 */
export function submit(p: Project, n: AilNode, files: Record<string, string>, by = "agent"): SubmitResult {
  const path = modulePath(p, n);
  if (!path || !isCompilable(p, n)) return { ok: false, node: n.name, error: `${n.name} is not a compilable node` };
  const extra = Object.keys(files).filter((f) => f !== path);
  if (extra.length) return { ok: false, node: n.name, error: `${n.name} may only write ${path}; refused ${extra.join(", ")}` };
  if (!(path in files)) return { ok: false, node: n.name, error: `no content for ${path}` };

  const abs = join(p.root, path);
  const backup = existsSync(abs) ? readFileSync(abs, "utf8") : null;
  mkdirSync(dirname(abs), { recursive: true });
  writeFileSync(abs, files[path]!);
  const verify = verifyNode(p, n, { checkDrift: false });
  if (!verify.ok) {
    if (backup === null) rmSync(abs); else writeFileSync(abs, backup);
    return { ok: false, node: n.name, verify, error: "verification failed; previous version restored" };
  }
  const lock = readLock(p);
  lock.nodes[n.name] = { hash: compileHash(p, n), files: { [path]: sha256(files[path]!) }, by };
  writeLock(p, lock);
  return { ok: true, node: n.name, verify };
}

// --- compile -----------------------------------------------------------------

export interface CompileOptions {
  provider: Provider;
  force?: boolean;
  maxAttempts?: number;
  temperature?: number;
  log?: (msg: string) => void;
}

export interface CompileOutcome { node: string; status: "fresh" | "compiled" | "stopped" | "failed"; attempts: number; detail: string }

export function compileTask(p: Project, n: AilNode): string {
  return [
    buildContext(p, n),
    "## Task",
    `Implement ${n.name} as specified. The only file you may write is ${modulePath(p, n)}.`,
    "Reply with exactly one block:",
    `=== FILE: ${modulePath(p, n)} ===`,
    "<complete file contents>",
    "=== END ===",
    "If you would have to choose anything the spec, profile, catalog or golden examples do not determine,",
    "and it is not listed in `free`, reply instead with a single line: STOP: <the question the spec must answer>",
  ].join("\n");
}

export async function compileNode(p: Project, n: AilNode, opts: CompileOptions, sample?: number): Promise<{ reply: ParsedReply; raw: string }> {
  const raw = await opts.provider.complete({
    system: loadSkill("ail-compile-leaf"),
    prompt: compileTask(p, n),
    temperature: opts.temperature,
    meta: { node: n.name, sample, purpose: "compile" },
  });
  return { reply: parseReply(raw), raw };
}

export async function compile(p: Project, names: string[], opts: CompileOptions): Promise<CompileOutcome[]> {
  const log = opts.log ?? (() => {});
  const glue = writeGlue(p);
  if (glue.length) log(`glue: wrote ${glue.join(", ")}`);
  const statuses = new Map(plan(p).map((e) => [e.node, e.status]));
  const targets = topoByUses(p, p.ordered.filter((n) => isCompilable(p, n) && (!names.length || names.includes(n.name))));
  const outcomes: CompileOutcome[] = [];
  for (const n of targets) {
    if (!opts.force && statuses.get(n.name) === "fresh") { outcomes.push({ node: n.name, status: "fresh", attempts: 0, detail: "cache hit" }); continue; }
    let prompt = compileTask(p, n);
    let outcome: CompileOutcome | null = null;
    const max = opts.maxAttempts ?? 3;
    for (let attempt = 1; attempt <= max && !outcome; attempt++) {
      log(`${n.name}: attempt ${attempt} with ${opts.provider.id}`);
      const raw = await opts.provider.complete({ system: loadSkill("ail-compile-leaf"), prompt, temperature: opts.temperature, meta: { node: n.name, sample: attempt - 1, purpose: "compile" } });
      const reply = parseReply(raw);
      if (reply.stop) { outcome = { node: n.name, status: "stopped", attempts: attempt, detail: reply.stop }; break; }
      const res = submit(p, n, reply.files, opts.provider.id);
      if (res.ok) { outcome = { node: n.name, status: "compiled", attempts: attempt, detail: res.verify?.checks.map((c) => c.kind).join(", ") ?? "" }; break; }
      const failures = res.verify ? res.verify.checks.filter((c) => !c.ok).map((c) => `- ${c.kind}: ${c.detail}`).join("\n") : `- ${res.error}`;
      log(`${n.name}: attempt ${attempt} rejected\n${failures}`);
      prompt = `${compileTask(p, n)}\n\n## Your previous attempt was rejected\n${failures}\n\nPrevious attempt:\n${raw}`;
    }
    outcomes.push(outcome ?? { node: n.name, status: "failed", attempts: max, detail: "no attempt passed verification: the node may be under-specified or infeasible" });
  }
  return outcomes;
}

// --- derive ------------------------------------------------------------------

/**
 * Derive tests from scenarios / verify sections. These become the oracle for
 * behaviour that `examples` cannot express. They are generated once, pinned
 * to the oracle hash, committed, and reviewed like any other code that
 * decides what "correct" means.
 */
export async function derive(p: Project, n: AilNode, provider: Provider): Promise<{ file: string; stop?: string }> {
  if (!needsDerivedCheck(n)) throw new Error(`${n.name} has no scenarios or verify section to derive checks from`);
  const ext = n.kind === "view" || n.kind === "flow" ? "tsx" : "ts";
  const rel = relative(p.root, join(checksDir(p), `${kebab(n.name)}.test.${ext}`));
  const header = `// ail-derived-from: ${n.name}@${oracleHash(p, n).slice(0, 16)}`;
  const raw = await provider.complete({
    system: loadSkill("ail-derive-checks"),
    prompt: [
      buildContext(p, n),
      "## Task",
      `Write the derived check file ${rel} for ${n.name}: one test per scenario (named exactly as the scenario) and one per verify item.`,
      `The module under test is ${modulePath(p, n)}; import it relative to ${rel}. The first line must be:`,
      header,
      "Reply with exactly one block:",
      `=== FILE: ${rel} ===`, "<complete file contents>", "=== END ===",
      "If a scenario cannot be checked without guessing, reply instead with: STOP: <question>",
    ].join("\n"),
    meta: { node: n.name, purpose: "derive" },
  });
  const reply = parseReply(raw);
  if (reply.stop) return { file: rel, stop: reply.stop };
  const body = reply.files[rel];
  if (!body) throw new Error(`model did not return ${rel}`);
  const old = derivedCheckFile(p, n).file;
  if (old && relative(p.root, old) !== rel) rmSync(old);
  mkdirSync(dirname(join(p.root, rel)), { recursive: true });
  writeFileSync(join(p.root, rel), body.startsWith("// ail-derived-from:") ? body.replace(/^.*\n/, header + "\n") : `${header}\n${body}`);
  return { file: rel };
}
