// `ail verify`: the IL is the oracle. Generated code is accepted only if it
// passes every check derived from its node.
//
//   exists     the module file is there
//   drift      the file matches what the lock says was generated
//   imports    the module imports only what its `uses` allow (encapsulation)
//   examples   `expr => expected` lines run as tests, translated mechanically
//   derived    tests derived once from scenarios/verify, pinned by oracle hash
//   typecheck  tsc over the project, when TypeScript is installed
import { existsSync, mkdirSync, readFileSync, readdirSync, writeFileSync } from "node:fs";
import { dirname, join, normalize, relative, resolve } from "node:path";
import { oracleHash } from "./hash.ts";

import { fileHash, readLock } from "./lock.ts";
import type { AilNode } from "./parse.ts";
import { AIL_HOME, isCompilable, kebab, modulePath, topoByUses, type Project } from "./project.ts";

export interface Check { kind: string; ok: boolean; severity: "error" | "warning"; detail: string }
export interface VerifyResult { node: string; ok: boolean; checks: Check[] }

const pass = (kind: string, detail = ""): Check => ({ kind, ok: true, severity: "error", detail });
const fail = (kind: string, detail: string, severity: "error" | "warning" = "error"): Check => ({ kind, ok: false, severity, detail });

export function runBunTest(cwd: string, files: string[]): { ok: boolean; failures: string[]; passes: number; output: string } {
  const r = Bun.spawnSync(["bun", "test", ...files.map((f) => (f.startsWith("/") ? f : "./" + f))], {
    cwd, env: { ...process.env, NO_COLOR: "1", FORCE_COLOR: "0" }, stdout: "pipe", stderr: "pipe",
  });
  const output = r.stdout.toString() + r.stderr.toString();
  const failures = [...output.matchAll(/^\(fail\)\s+(.*)$/gm)].map((m) => m[1]!.trim());
  const passes = Number(/^\s*(\d+) pass/m.exec(output)?.[1] ?? 0);
  return { ok: r.exitCode === 0, failures, passes, output };
}

/** Modules a node may import, as normalized paths without extension. */
function allowedImports(p: Project, n: AilNode): { relative: Set<string>; packages: string[] } {
  const strip = (s: string) => normalize(s).replace(/\.(tsx?|css)$/, "");
  const rel = new Set<string>();
  for (const u of n.uses) { const d = p.nodes.get(u); const mp = d && modulePath(p, d); if (mp) rel.add(strip(mp)); }
  const s = p.target?.settings ?? {};
  if (s["tokens-css"]) rel.add(strip(s["tokens-css"]));
  return { relative: rel, packages: (s["libs"] ?? "").split(/[\s,]+/).filter(Boolean) };
}

export function checkImports(p: Project, n: AilNode, source: string): Check {
  const path = modulePath(p, n)!;
  const allowed = allowedImports(p, n);
  const bad: string[] = [];
  for (const m of source.matchAll(/(?:^|\n)\s*(?:import|export)\s[^"'\n]*?from\s*["']([^"']+)["']|(?:^|\n)\s*import\s*["']([^"']+)["']/g)) {
    const spec = m[1] ?? m[2]!;
    if (spec.startsWith(".")) {
      const target = normalize(join(dirname(path), spec)).replace(/\.(tsx?|css)$/, "");
      if (!allowed.relative.has(target) && !allowed.relative.has(target + "/index")) bad.push(spec);
    } else if (!allowed.packages.some((pkg) => spec === pkg || spec.startsWith(pkg + "/"))) bad.push(spec);
  }
  return bad.length
    ? fail("imports", `imports outside its \`uses\` and the target's libs: ${bad.join(", ")} — add the dependency to \`uses\` in the IL, or remove the import`)
    : pass("imports");
}

export function examplesTestSource(p: Project, n: AilNode): string {
  const abs = (rel: string) => resolve(p.root, rel);
  const deps = n.uses.map((u) => p.nodes.get(u)).filter((d): d is AilNode => !!d && !!modulePath(p, d));
  const lines = [
    `// Generated by \`ail check\` from the examples of ${n.name}. Do not edit.`,
    `import { test, expect } from "bun:test";`,
    ...deps.map((d, i) => `import * as __d${i} from ${JSON.stringify(abs(modulePath(p, d)!))};`),
    `import * as __self from ${JSON.stringify(abs(modulePath(p, n)!))};`,
    `const __scope: Record<string, unknown> = { ${deps.map((_, i) => `...__d${i}, `).join("")}...__self };`,
    `const __eval = (src: string) => new Function(...Object.keys(__scope), "return (" + src + ");")(...Object.values(__scope));`,
  ];
  n.examples.forEach((e, i) => {
    lines.push(`test(${JSON.stringify(`${n.name} example ${i + 1}: ${e.expr} => ${e.expected}`)}, () => {`);
    lines.push(`  expect(__eval(${JSON.stringify(e.expr)})).toEqual(__eval(${JSON.stringify(e.expected)}));`);
    lines.push(`});`);
  });
  return lines.join("\n") + "\n";
}

export const checksDir = (p: Project) => join(p.root, p.config.checksDir ?? "checks");

export function derivedCheckFile(p: Project, n: AilNode): { file: string | null; pinned: string | null } {
  const dir = join(checksDir(p), n.dir);
  if (!existsSync(dir)) return { file: null, pinned: null };
  const name = readdirSync(dir).find((f) => f === `${kebab(n.name)}.test.ts` || f === `${kebab(n.name)}.test.tsx`);
  if (!name) return { file: null, pinned: null };
  const file = join(dir, name);
  const pinned = /ail-derived-from:\s*\w+@([0-9a-f]+)/.exec(readFileSync(file, "utf8"))?.[1] ?? null;
  return { file, pinned };
}

export function needsDerivedCheck(n: AilNode): boolean {
  return n.scenarios.length > 0 || n.sections.some((s) => s.key === "verify");
}

export function verifyNode(p: Project, n: AilNode, opts: { checkDrift?: boolean } = {}): VerifyResult {
  const checks: Check[] = [];
  const path = modulePath(p, n);
  if (!path) return { node: n.name, ok: true, checks: [pass("exists", "not compilable; nothing to verify")] };
  const abs = join(p.root, path);
  if (!existsSync(abs)) return { node: n.name, ok: false, checks: [fail("exists", `${path} does not exist; run \`ail build\``)] };
  checks.push(pass("exists", path));

  if (opts.checkDrift !== false) {
    const entry = readLock(p).nodes[n.name];
    const actual = fileHash(p, path);
    if (!entry) checks.push(fail("drift", "not recorded in ail.lock.json (compile or submit it through ail)", "warning"));
    else if (entry.files[path] !== actual) checks.push(fail("drift", `${path} differs from the generated version; change the spec instead and rebuild`));
    else checks.push(pass("drift"));
  }

  checks.push(checkImports(p, n, readFileSync(abs, "utf8")));

  const testFiles: string[] = [];
  if (n.examples.length) {
    const dir = join(p.root, ".ail", "verify");
    mkdirSync(dir, { recursive: true });
    const f = join(dir, `${kebab(n.name)}.examples.test.ts`);
    writeFileSync(f, examplesTestSource(p, n));
    testFiles.push(f);
  }
  if (needsDerivedCheck(n)) {
    const { file, pinned } = derivedCheckFile(p, n);
    const want = oracleHash(p, n).slice(0, 16);
    if (!file) checks.push(fail("derived", `scenarios/verify have no derived check; \`ail build\` derives it`, "warning"));
    else if (pinned !== want) checks.push(fail("derived", `${file.slice(p.root.length + 1)} was derived from an older spec (${pinned} ≠ ${want}); re-derive and review`));
    else testFiles.push(file);
  }
  if (testFiles.length) {
    const r = runBunTest(p.root, testFiles);
    if (r.ok) checks.push(pass("tests", `${r.passes} passed`));
    else checks.push(fail("tests", r.failures.length ? r.failures.map((f) => "✗ " + f).join("\n") : r.output.trim().split("\n").slice(-25).join("\n")));
  }
  return { node: n.name, ok: checks.every((c) => c.ok || c.severity === "warning"), checks };
}

export function typecheck(p: Project): Check | null {
  const tsc = join(p.root, "node_modules", "typescript", "bin", "tsc");
  if (!existsSync(tsc) || !existsSync(join(p.root, "tsconfig.json"))) return null;
  const r = Bun.spawnSync(["bun", tsc, "--noEmit", "-p", p.root], { cwd: p.root, stdout: "pipe", stderr: "pipe" });
  const out = (r.stdout.toString() + r.stderr.toString()).trim();
  return r.exitCode === 0 ? pass("typecheck") : fail("typecheck", out.split("\n").slice(0, 30).join("\n"));
}

export function verifyProject(p: Project, names?: string[]): { results: VerifyResult[]; typecheck: Check | null; ok: boolean } {
  const targets = topoByUses(p, p.ordered.filter((n) => isCompilable(p, n) && (!names?.length || names.includes(n.name))));
  const results = targets.map((n) => verifyNode(p, n));
  const tc = typecheck(p);
  return { results, typecheck: tc, ok: results.every((r) => r.ok) && (tc?.ok ?? true) };
}

export function formatVerify(r: { results: VerifyResult[]; typecheck: Check | null; ok: boolean }): string {
  const out: string[] = [];
  for (const res of r.results) {
    out.push(`${res.ok ? "✓" : "✗"} ${res.node}`);
    for (const c of res.checks) {
      const mark = c.ok ? "  ✓" : c.severity === "warning" ? "  !" : "  ✗";
      out.push(`${mark} ${c.kind.padEnd(10)} ${c.detail.split("\n").join("\n               ")}`);
    }
  }
  if (r.typecheck) out.push(`${r.typecheck.ok ? "✓" : "✗"} typecheck ${r.typecheck.detail}`);
  out.push(r.ok ? "\nall checks passed" : "\nverification FAILED");
  return out.join("\n");
}

/** Model instructions shipped with ail (prompts/<name>.md). */
export function loadPrompt(name: string): string {
  return readFileSync(join(AIL_HOME, "prompts", `${name}.md`), "utf8").trim();
}

/** Where a node's derived check lives: checks/<dir>/<kebab>.test.ts(x). */
export function checkPath(p: Project, n: AilNode): string {
  const ext = n.kind === "view" || n.kind === "flow" ? "tsx" : "ts";
  return relative(p.root, join(checksDir(p), n.dir, `${kebab(n.name)}.test.${ext}`));
}

export const checkHeader = (p: Project, n: AilNode) => `// ail-derived-from: ${n.name}@${oracleHash(p, n).slice(0, 16)}`;

/** Make sure a derived check starts with the header pinning it to the current spec. */
export function stampCheck(p: Project, n: AilNode, body: string): string {
  const header = checkHeader(p, n);
  return body.startsWith("// ail-derived-from:") ? body.replace(/^.*\n/, header + "\n") : `${header}\n${body}`;
}
